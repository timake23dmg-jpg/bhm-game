// Generates supabase/questions.sql from src/data/questions.json (the single source of truth).
import { readFileSync, writeFileSync } from 'node:fs'

const questions = JSON.parse(readFileSync(new URL('../src/data/questions.json', import.meta.url), 'utf8'))
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`
const arr = (a) => (a.length ? `array[${a.map(lit).join(', ')}]` : `'{}'::text[]`)

const rows = questions.map((q) =>
  `  (${lit(q.id)}, ${lit(q.category)}, ${lit(q.prompt)}, ${lit(q.answer)}, ${arr(q.alternateSpellings)}, ${arr(q.suggestedLies)}, ${q.isFinal})`)

const sql = `-- Generated by scripts/gen-questions-sql.mjs from src/data/questions.json. Do not edit by hand.
-- Replaces the whole question bank: questions no longer in the file are removed.
begin;
delete from bhm.questions where id not in (${questions.map((q) => lit(q.id)).join(', ')});
insert into bhm.questions (id, category, prompt, answer, alternate_spellings, suggested_lies, is_final) values
${rows.join(',\n')}
on conflict (id) do update set
  category = excluded.category, prompt = excluded.prompt, answer = excluded.answer,
  alternate_spellings = excluded.alternate_spellings, suggested_lies = excluded.suggested_lies,
  is_final = excluded.is_final;
commit;
`
writeFileSync(new URL('../supabase/questions.sql', import.meta.url), sql)
console.log(`Wrote ${questions.length} questions to supabase/questions.sql`)
